        GWI_NRCALC,
        SUM(GWI_VLFRET) AS TotalFrete
    FROM [STAGE].[gfe].[GWI]
    WHERE ISNULL(D_E_L_E_T_, '') <> '*'
    GROUP BY GWI_NRCALC
